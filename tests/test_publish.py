"""PR draft and Gate 2 preparation: the PR only claims what ran, and stale fixes are caught."""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from nightshift.db import Repo, Task
from nightshift.worker import prwriter, publish
from nightshift.worker.publish import branch_name, prepare
from nightshift.worker.verify import CommandResult, FixCheck


def _result(command: str, ok: bool, tail: str) -> CommandResult:
    return CommandResult(command=command, ok=ok, exit_code=0 if ok else 1, timed_out=False, seconds=1.0, tail=tail)


CHECK = FixCheck(
    passed=True,
    test_files=["tests/test_calc.py"],
    source_files=["calc.py"],
    fails_without_fix=_result("pytest tests/test_calc.py", False, "E   assert -1 == 5\n1 failed"),
    passes_with_fix=_result("pytest tests/test_calc.py", True, "1 passed"),
    suite=[_result("pytest", True, "40 passed")],
)


def test_pr_body_closes_the_issue_and_carries_real_evidence() -> None:
    draft = prwriter.PRDraft(title="fix: add", summary="Fixes the sign in `add`.", commit_message="fix: add\n\nbody")
    body = prwriter.pr_body(draft, CHECK, 12)
    assert body.startswith("Closes #12")
    assert "assert -1 == 5" in body and "1 passed" in body
    assert "- `pytest`: passed" in body


def test_pr_body_keeps_an_existing_closing_line() -> None:
    draft = prwriter.PRDraft(title="t", summary="Fixes #12. Details.", commit_message="m")
    assert not prwriter.pr_body(draft, CHECK, 12).startswith("Closes")


def test_the_attribution_line_is_added_at_gate_2_not_by_the_writer() -> None:
    draft = prwriter.PRDraft(title="t", summary="s", commit_message="fix: add\n\nbody")
    assert prwriter.commit_message(draft) == "fix: add\n\nbody\n"
    assert publish.with_attribution(prwriter.commit_message(draft), "Generated by NightShift").endswith(
        "body\n\nGenerated by NightShift\n"
    )


def _git(cwd: Path, *args: str) -> str:
    env_args = ["-c", "user.email=t@t", "-c", "user.name=t", "-c", "init.defaultBranch=main"]
    return subprocess.run(["git", *env_args, *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


@pytest.fixture
def upstream(tmp_path: Path) -> tuple[Path, str]:
    """A repo with a base commit, then a later upstream commit that changes a.py only."""
    src = tmp_path / "upstream"
    src.mkdir()
    _git(src, "init", "-q")
    (src / "a.py").write_text("x = 1\n")
    (src / "b.py").write_text("y = 1\n")
    _git(src, "add", "-A")
    _git(src, "commit", "-qm", "base")
    base = _git(src, "rev-parse", "HEAD").strip()
    (src / "a.py").write_text("x = 2\n")
    _git(src, "commit", "-qam", "upstream moves on")
    return src, base


def _task(base: str, diff: str) -> Task:
    return Task(id=7, issue_number=3, base_commit=base, diff=diff, issue={"title": "Fix the Thing!"}, plan={},
                result={}, rehearsal=False)  # fmt: skip


async def test_prepare_blocks_a_fix_whose_files_changed_upstream(upstream: tuple[Path, str], tmp_path: Path) -> None:
    src, base = upstream
    diff = "--- a/a.py\n+++ b/a.py\n@@ -1 +1 @@\n-x = 1\n+x = 3\n"
    task = _task(base, diff)
    with pytest.raises(Exception, match="apply"):  # the context no longer matches either
        await prepare(Repo(full_name="o/r"), task, tmp_path / "wd", url=str(src))


async def test_prepare_applies_a_fix_on_untouched_files(upstream: tuple[Path, str], tmp_path: Path) -> None:
    src, base = upstream
    diff = "--- a/b.py\n+++ b/b.py\n@@ -1 +1 @@\n-y = 1\n+y = 2\n"
    prepared = await prepare(Repo(full_name="o/r"), _task(base, diff), tmp_path / "wd", url=str(src))
    assert prepared.drift == []
    assert prepared.files == ["b.py"]
    assert prepared.branch == "nightshift/3-fix-the-thing"
    assert (tmp_path / "wd" / "b.py").read_text() == "y = 2\n"


async def test_drift_is_reported_even_when_the_patch_still_applies(tmp_path: Path) -> None:
    """Upstream edited another part of a file the fix touches: the patch applies, but the fix was
    verified against code that no longer exists, so publishing must stop."""
    src = tmp_path / "upstream"
    src.mkdir()
    _git(src, "init", "-q")
    lines = [f"v{i} = {i}" for i in range(30)]
    (src / "a.py").write_text("\n".join(lines) + "\n")
    _git(src, "add", "-A")
    _git(src, "commit", "-qm", "base")
    base = _git(src, "rev-parse", "HEAD").strip()
    (src / "a.py").write_text("\n".join([*lines[:25], "v25 = 99", *lines[26:]]) + "\n")
    _git(src, "commit", "-qam", "upstream edits the end of a.py")
    diff = "--- a/a.py\n+++ b/a.py\n@@ -1,3 +1,3 @@\n-v0 = 0\n+v0 = -1\n v1 = 1\n v2 = 2\n"
    prepared = await prepare(Repo(full_name="o/r"), _task(base, diff), tmp_path / "wd", url=str(src))
    assert prepared.drift == ["a.py"]


def test_branch_name_is_short_and_safe() -> None:
    task = _task("x", "")
    task.issue = {"title": "Persist Tool Call References in Chat (UI + API) ünïcode!!"}
    assert branch_name(task) == "nightshift/3-persist-tool-call-references-in-chat-ui"


# ---------- follow-ups on a published PR ----------

PUBLISHED = "--- a/b.py\n+++ b/b.py\n@@ -1 +1 @@\n-y = 1\n+y = 2\n"
REVISED = "--- a/b.py\n+++ b/b.py\n@@ -1 +1,2 @@\n-y = 1\n+y = 2\n+z = 3\n"


@pytest.fixture
def pr_branch(upstream: tuple[Path, str], tmp_path: Path) -> publish.PullInfo:
    """The operator's fork, with the published fix on its PR branch (on top of the later upstream commit)."""
    src, base = upstream
    fork = tmp_path / "fork"
    _git(tmp_path, "clone", "-q", str(src), str(fork))
    _git(fork, "checkout", "-q", "-b", "nightshift/3-fix")
    (fork / "b.py").write_text("y = 2\n")
    _git(fork, "commit", "-qam", "fix: the thing")
    return publish.PullInfo(number=9, url="https://github.com/o/r/pull/9", state="OPEN", head_owner="me",
                            head_branch="nightshift/3-fix", head_url=str(fork))  # fmt: skip


async def test_a_follow_up_stages_only_what_the_revision_changed(
    upstream: tuple[Path, str], pr_branch: publish.PullInfo, tmp_path: Path
) -> None:
    src, base = upstream
    prepared = await publish.prepare_follow_up(
        Repo(full_name="o/r"), _task(base, REVISED), pr_branch, PUBLISHED, tmp_path / "wd", url=str(src)
    )
    wd = tmp_path / "wd"
    assert prepared.branch == "nightshift/3-fix" and prepared.files == ["b.py"]
    assert (wd / "b.py").read_text() == "y = 2\nz = 3\n"
    assert (wd / "a.py").read_text() == "x = 2\n"  # the PR branch's own base is kept, not the task's
    staged = _git(wd, "diff", "--cached")
    assert "+z = 3" in staged and "-y = 1" not in staged  # one more line, not the whole fix again


async def test_a_follow_up_with_nothing_new_is_refused(
    upstream: tuple[Path, str], pr_branch: publish.PullInfo, tmp_path: Path
) -> None:
    src, base = upstream
    with pytest.raises(publish.PublishError, match="nothing to push"):
        await publish.prepare_follow_up(
            Repo(full_name="o/r"), _task(base, PUBLISHED), pr_branch, PUBLISHED, tmp_path / "wd", url=str(src)
        )


async def test_a_follow_up_needs_an_open_pr_on_your_fork(pr_branch: publish.PullInfo, tmp_path: Path) -> None:
    closed = pr_branch.model_copy(update={"state": "MERGED"})
    with pytest.raises(publish.PublishError, match="merged"):
        await publish.prepare_follow_up(Repo(full_name="o/r"), _task("x", REVISED), closed, PUBLISHED, tmp_path)
    theirs = pr_branch.model_copy(update={"head_owner": "someone-else"})
    staged = publish.FollowUp(workdir=str(tmp_path), branch="b", files=[])
    with pytest.raises(publish.PublishError, match="someone-else's fork"):
        await publish.push_follow_up(Repo(full_name="o/r"), _task("x", REVISED), theirs, staged, message="m")


async def test_only_a_pr_of_the_same_repo_can_be_attached() -> None:
    with pytest.raises(publish.PublishError, match="not a pull request of o/r"):
        await publish.pull_info(Repo(full_name="o/r"), "https://github.com/other/repo/pull/1")
    with pytest.raises(publish.PublishError):
        await publish.pull_info(Repo(full_name="o/r"), "https://github.com/o/r/issues/1")
