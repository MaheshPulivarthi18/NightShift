"""PR draft and Gate 2 preparation: the PR only claims what ran, and stale fixes are caught."""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from nightshift.db import Repo, Task
from nightshift.worker import prwriter
from nightshift.worker.publish import branch_name, prepare
from nightshift.worker.verify import CommandResult, FixCheck


def _result(command: str, ok: bool, tail: str) -> CommandResult:
    return CommandResult(command=command, ok=ok, exit_code=0 if ok else 1, timed_out=False, seconds=1.0, tail=tail)


CHECK = FixCheck(
    passed=True,
    test_files=["tests/test_calc.py"],
    source_files=["calc.py"],
    fails_without_fix=_result("pytest tests/test_calc.py", False, "E   assert -1 == 5\n1 failed"),
    passes_with_fix=_result("pytest tests/test_calc.py", True, "1 passed"),
    suite=[_result("pytest", True, "40 passed")],
)


def test_pr_body_closes_the_issue_and_carries_real_evidence() -> None:
    draft = prwriter.PRDraft(title="fix: add", summary="Fixes the sign in `add`.", commit_message="fix: add\n\nbody")
    body = prwriter.pr_body(draft, CHECK, 12)
    assert body.startswith("Closes #12")
    assert "assert -1 == 5" in body and "1 passed" in body
    assert "- `pytest`: passed" in body


def test_pr_body_keeps_an_existing_closing_line() -> None:
    draft = prwriter.PRDraft(title="t", summary="Fixes #12. Details.", commit_message="m")
    assert not prwriter.pr_body(draft, CHECK, 12).startswith("Closes")


def test_commit_message_ends_with_attribution() -> None:
    draft = prwriter.PRDraft(title="t", summary="s", commit_message="fix: add\n\nbody")
    assert prwriter.commit_message(draft).rstrip().endswith("Generated by NightShift")


def _git(cwd: Path, *args: str) -> str:
    env_args = ["-c", "user.email=t@t", "-c", "user.name=t", "-c", "init.defaultBranch=main"]
    return subprocess.run(["git", *env_args, *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


@pytest.fixture
def upstream(tmp_path: Path) -> tuple[Path, str]:
    """A repo with a base commit, then a later upstream commit that changes a.py only."""
    src = tmp_path / "upstream"
    src.mkdir()
    _git(src, "init", "-q")
    (src / "a.py").write_text("x = 1\n")
    (src / "b.py").write_text("y = 1\n")
    _git(src, "add", "-A")
    _git(src, "commit", "-qm", "base")
    base = _git(src, "rev-parse", "HEAD").strip()
    (src / "a.py").write_text("x = 2\n")
    _git(src, "commit", "-qam", "upstream moves on")
    return src, base


def _task(base: str, diff: str) -> Task:
    return Task(id=7, issue_number=3, base_commit=base, diff=diff, issue={"title": "Fix the Thing!"}, plan={},
                result={}, rehearsal=False)  # fmt: skip


async def test_prepare_blocks_a_fix_whose_files_changed_upstream(upstream: tuple[Path, str], tmp_path: Path) -> None:
    src, base = upstream
    diff = "--- a/a.py\n+++ b/a.py\n@@ -1 +1 @@\n-x = 1\n+x = 3\n"
    task = _task(base, diff)
    with pytest.raises(Exception, match="apply"):  # the context no longer matches either
        await prepare(Repo(full_name="o/r"), task, tmp_path / "wd", url=str(src))


async def test_prepare_applies_a_fix_on_untouched_files(upstream: tuple[Path, str], tmp_path: Path) -> None:
    src, base = upstream
    diff = "--- a/b.py\n+++ b/b.py\n@@ -1 +1 @@\n-y = 1\n+y = 2\n"
    prepared = await prepare(Repo(full_name="o/r"), _task(base, diff), tmp_path / "wd", url=str(src))
    assert prepared.drift == []
    assert prepared.files == ["b.py"]
    assert prepared.branch == "nightshift/3-fix-the-thing"
    assert (tmp_path / "wd" / "b.py").read_text() == "y = 2\n"


async def test_drift_is_reported_even_when_the_patch_still_applies(tmp_path: Path) -> None:
    """Upstream edited another part of a file the fix touches: the patch applies, but the fix was
    verified against code that no longer exists, so publishing must stop."""
    src = tmp_path / "upstream"
    src.mkdir()
    _git(src, "init", "-q")
    lines = [f"v{i} = {i}" for i in range(30)]
    (src / "a.py").write_text("\n".join(lines) + "\n")
    _git(src, "add", "-A")
    _git(src, "commit", "-qm", "base")
    base = _git(src, "rev-parse", "HEAD").strip()
    (src / "a.py").write_text("\n".join([*lines[:25], "v25 = 99", *lines[26:]]) + "\n")
    _git(src, "commit", "-qam", "upstream edits the end of a.py")
    diff = "--- a/a.py\n+++ b/a.py\n@@ -1,3 +1,3 @@\n-v0 = 0\n+v0 = -1\n v1 = 1\n v2 = 2\n"
    prepared = await prepare(Repo(full_name="o/r"), _task(base, diff), tmp_path / "wd", url=str(src))
    assert prepared.drift == ["a.py"]


