from pathlib import Path
from typing import Any

import pytest
from sqlalchemy import delete

from nightshift.db import Repo, Task, session_scope
from nightshift.worker import prwriter, publish
from nightshift.worker import task as worker
from nightshift.worker.verify import CommandResult, FixCheck

TEMPLATE = "## Description\n\n## Type of Change\n\n- [ ] Bug fix\n\n## Testing\n"
FAILING = CommandResult(command="pytest tests/slow -q", ok=False, exit_code=1, timed_out=False, seconds=1, tail="")
PASSING = CommandResult(command="pytest tests/unit -q", ok=True, exit_code=0, timed_out=False, seconds=1, tail="")


def test_publish_helpers() -> None:
    assert publish.template_headings(TEMPLATE) == ["Description", "Type of Change", "Testing"]
    assert publish.missing_sections(
        "## Description\nx\n### testing\n", ["Description", "Type of Change", "Testing"]
    ) == ["Type of Change"]
    assert publish.with_attribution("fix: a\n\nbody", "") == "fix: a\n\nbody\n"
    assert publish.with_attribution("fix: a", "Made with X") == "fix: a\n\nMade with X\n"
    assert publish.strip_attribution("fix: a\n\nGenerated by NightShift\n") == "fix: a"
    for good in ("nightshift/110-docs", "fix-110", "a.b/c_d"):
        assert publish.BRANCH_RE.match(good), good
    for bad in ("../x", "a..b", "/a", "a/", "a b", "a//b", "x."):
        assert not publish.BRANCH_RE.match(bad), bad


def test_evidence_goes_where_the_template_put_the_marker() -> None:
    check = FixCheck(passed=True, kind="docs", test_files=[], source_files=["README.md"], suite=[PASSING])
    draft = prwriter.PRDraft(title="t", summary="## Description\nx\n\n## Testing\n<!-- testing -->\n\n## Notes\ny",
                             commit_message="docs: x")  # fmt: skip
    body = prwriter.pr_body(draft, check, 7)
    assert body.startswith("Closes #7") and prwriter.TESTING_MARK not in body
    assert body.index("Documentation-only change") < body.index("## Notes")  # in place, not appended
    assert body.count("## Testing") == 1


