async def test_gate2_shows_what_goes_out_and_blocks_a_missing_template_section(ready: dict[str, Any]) -> None:
    info = await worker.gate2(ready["task"], confirm=True)
    assert not info["published"]
    assert any("Type of Change" in b for b in info["blockers"])
    assert info["commit_message"] == "fix: a"  # the old attribution line is shown separately
    assert info["attribution"] == "Generated by NightShift"
    assert any("failing suites" in w and "tests/slow" in w for w in info["warnings"])
    assert info["branch"] == "nightshift/7-a-bug"


async def test_gate2_publishes_the_edited_pr_and_remembers_the_repo_settings(ready: dict[str, Any]) -> None:
    body = "## Description\nfixed\n\n## Type of Change\n- [x] Bug fix\n\n## Testing\nran"
    edits = {"body": body, "attribution": "", "branch": "fix/7-a-bug"}
    info = await worker.gate2(ready["task"], confirm=True, edits=edits, remember=True)
    assert info["published"] and not info["blockers"]
    assert ready["sent"]["message"] == "fix: a\n"  # no attribution line
    assert ready["sent"]["body"] == body and ready["sent"]["branch"] == "fix/7-a-bug"
    async with session_scope() as s:
        repo = await s.get(Repo, ready["repo"])
        task = await s.get(Task, ready["task"])
    assert repo is not None and repo.publish == {"attribution": "", "branch_prefix": "fix"}
    assert task is not None and task.status == "published" and task.result["published_diff"] == "d"
    assert publish.attribution_for(repo) == "" and publish.branch_name(task, repo) == "fix/7-a-bug"
